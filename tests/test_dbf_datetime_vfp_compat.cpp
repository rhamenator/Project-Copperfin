std::string read_file(const fs::path &path) {
    std::ifstream in(path, std::ios::binary);
    return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

std::vector<std::string> split_lines(const std::string &output) {
    std::vector<std::string> lines;
    for (std::size_t start = 0U; start < output.size();) {
        const std::size_t end = output.find('\n', start);
        lines.push_back(output.substr(start, end == std::string::npos ? std::string::npos : end - start));
        if (end == std::string::npos) {
            break;
        }
        start = end + 1U;
    }
    return lines;
}

bool run(const fs::path &dir, const std::string &name, const std::string &prg, std::string &message) {
    write_text(dir / (name + ".prg"), prg);
    auto session = copperfin::runtime::PrgRuntimeSession::create(
        make_runtime_session_options((dir / (name + ".prg")).string(), dir.string(), false));
    const auto state = session.run(copperfin::runtime::DebugResumeAction::continue_run);
    message = state.message;
    return state.completed;
}

void write_bytes(const fs::path &path, const unsigned char *bytes, const std::size_t size) {
    std::ofstream out(path, std::ios::binary);
    out.write(reinterpret_cast<const char *>(bytes), static_cast<std::streamsize>(size));
}

// A table VFP9 wrote is read as the values VFP9 shows.
void test_vfp_written_datetimes_are_read_as_vfp_shows_them() {
    const fs::path dir = fs::temp_directory_path() / "copperfin_datetime_vfp_read";
    std::error_code ignored;
    fs::remove_all(dir, ignored);
    fs::create_directories(dir);
    write_bytes(dir / "dt.dbf", kVfpDateTimeTable, sizeof(kVfpDateTimeTable));
    std::string message;
    const bool completed = run(dir, "read",
        "LOCAL c\nc = ''\nUSE dt\nSCAN\n"
        "    c = c + IIF(ISNULL(t), 'NULL', TTOC(t, 1) + '/' + DTOC(TTOD(t), 1)) + CHR(10)\n"
        "ENDSCAN\nSTRTOFILE(c, 'read.txt')\nRETURN\n", message);
    expect(completed, "DateTime read: the script should complete: " + message);
    const std::vector<std::string> expected = {
        "20200102030405/20200102", "20240506121314/20240506", "20191231235959/20191231", "NULL"};
    const std::vector<std::string> lines = split_lines(read_file(dir / "read.txt"));
    expect(lines.size() >= expected.size(), "DateTime read: one result per record, got " + std::to_string(lines.size()));
    for (std::size_t index = 0U; index < expected.size() && index < lines.size(); ++index) {
        expect(lines[index] == expected[index],
            "DateTime read: record " + std::to_string(index + 1U) + " expected [" + expected[index] + "], got [" +
                lines[index] + "]");
    }
    fs::remove_all(dir, ignored);
}

// VFP9 rounds the stored milliseconds to the nearest second (half up), carrying into the next day.
void test_stored_milliseconds_round_to_the_nearest_second() {
    const fs::path dir = fs::temp_directory_path() / "copperfin_datetime_vfp_millis";
    std::error_code ignored;
    fs::remove_all(dir, ignored);
    fs::create_directories(dir);
    write_bytes(dir / "ms.dbf", kVfpMillisecondTable, sizeof(kVfpMillisecondTable));
    std::string message;
    const bool completed = run(dir, "millis",
        "LOCAL c\nc = ''\nUSE ms\nSCAN\n"
        "    c = c + TTOC(t, 1) + CHR(10)\n"
        "ENDSCAN\nSTRTOFILE(c, 'millis.txt')\nRETURN\n", message);
    expect(completed, "DateTime milliseconds: the script should complete: " + message);
    // Record 10 (86399500 ms) is left out, see the comment on kVfpMillisecondTable.
    const std::vector<std::string> expected = {
        "20191231000000", "20191231000000", "20191231000000", "20191231000001", "20191231000001",
        "20191231000001", "20191231000001", "20191231235959", "20191231235959", "",
        "20200101000000", "20200101000000", "20200101000001"};
    const std::vector<std::string> lines = split_lines(read_file(dir / "millis.txt"));
    expect(lines.size() >= expected.size(), "DateTime milliseconds: one result per record, got " + std::to_string(lines.size()));
    for (std::size_t index = 0U; index < expected.size() && index < lines.size(); ++index) {
        if (index == 9U) {
            continue;
        }
        expect(lines[index] == expected[index],
            "DateTime milliseconds: record " + std::to_string(index + 1U) + " expected [" + expected[index] +
                "], got [" + lines[index] + "]");
    }
    fs::remove_all(dir, ignored);
}

// A table Copperfin writes stores the Julian Day Number VFP9 stores for the same DateTime. The milliseconds are the exact
// time of day (VFP9 itself adds a stray millisecond, which does not change the displayed second).
void test_copperfin_written_datetimes_use_vfp_julian_day_numbers() {
    const fs::path dir = fs::temp_directory_path() / "copperfin_datetime_vfp_write";
    std::error_code ignored;
    fs::remove_all(dir, ignored);
    fs::create_directories(dir);
    std::string message;
    const bool completed = run(dir, "write",
        "CREATE TABLE tt (t T)\n"
        "INSERT INTO tt (t) VALUES ({^2019-12-31 23:59:59})\n"
        "INSERT INTO tt (t) VALUES ({^2020-01-02 03:04:05})\n"
        "INSERT INTO tt (t) VALUES ({^2024-05-06 12:13:14})\n"
        "USE\nRETURN\n", message);
    expect(completed, "DateTime write: the script should complete: " + message);
    const std::string bytes = read_file(dir / "tt.dbf");
    expect(bytes.size() > 12U, "DateTime write: the table should exist");
    if (bytes.size() > 12U) {
        const auto le16 = [&](const std::size_t offset) {
            return static_cast<std::size_t>(static_cast<unsigned char>(bytes[offset])) |
                   (static_cast<std::size_t>(static_cast<unsigned char>(bytes[offset + 1U])) << 8U);
        };
        const auto le32 = [&](const std::size_t offset) {
            return static_cast<std::uint32_t>(static_cast<unsigned char>(bytes[offset])) |
                   (static_cast<std::uint32_t>(static_cast<unsigned char>(bytes[offset + 1U])) << 8U) |
                   (static_cast<std::uint32_t>(static_cast<unsigned char>(bytes[offset + 2U])) << 16U) |
                   (static_cast<std::uint32_t>(static_cast<unsigned char>(bytes[offset + 3U])) << 24U);
        };
        const std::size_t header = le16(8U);
        const std::size_t record_length = le16(10U);
        struct Expected {
            std::uint32_t julian;
            std::uint32_t milliseconds;
        };
        const std::vector<Expected> expected = {{2458849U, 86399000U}, {2458851U, 11045000U}, {2460437U, 43994000U}};
        for (std::size_t index = 0U; index < expected.size(); ++index) {
            const std::size_t field = header + (index * record_length) + 1U;   // after the deletion flag
            if (field + 8U > bytes.size()) {
                expect(false, "DateTime write: record " + std::to_string(index + 1U) + " is missing");
                continue;
            }
            expect(le32(field) == expected[index].julian,
                "DateTime write: record " + std::to_string(index + 1U) + " Julian day expected " +
                    std::to_string(expected[index].julian) + ", got " + std::to_string(le32(field)));
            expect(le32(field + 4U) == expected[index].milliseconds,
                "DateTime write: record " + std::to_string(index + 1U) + " milliseconds expected " +
                    std::to_string(expected[index].milliseconds) + ", got " + std::to_string(le32(field + 4U)));
        }
    }
    fs::remove_all(dir, ignored);
}

// A corrupt table can hold the largest Julian day together with milliseconds that round past midnight; reading it must
// not overflow the carried day, and the value is not a DateTime (#6759 review).
void test_corrupt_julian_day_carry_is_rejected() {
    const fs::path dir = fs::temp_directory_path() / "copperfin_datetime_corrupt_julian";
    std::error_code ignored;
    fs::remove_all(dir, ignored);
    fs::create_directories(dir);
    std::string bytes(reinterpret_cast<const char *>(kVfpMillisecondTable), sizeof(kVfpMillisecondTable));
    // Records 1 and 2 of ms.dbf: Julian day 2147483647 with 86400000 ms (rounds past midnight) and with 0 ms.
    constexpr std::size_t kHeader = 488U;
    constexpr std::size_t kRecord = 48U;
    constexpr std::size_t kField = 9U;   // the T field offset within a record
    const auto patch = [&](const std::size_t record, const std::uint32_t julian, const std::uint32_t millis) {
        const std::size_t at = kHeader + (record * kRecord) + kField;
        for (std::size_t index = 0U; index < 4U; ++index) {
            bytes[at + index] = static_cast<char>((julian >> (8U * index)) & 0xFFU);
            bytes[at + 4U + index] = static_cast<char>((millis >> (8U * index)) & 0xFFU);
        }
    };
    patch(0U, 2147483647U, 86400000U);
    patch(1U, 2147483647U, 0U);
    {
        std::ofstream out(dir / "ms.dbf", std::ios::binary);
        out.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
    }
    std::string message;
    const bool completed = run(dir, "corrupt",
        "LOCAL c\nc = ''\nUSE ms\nGO 1\nc = c + '[' + VARTYPE(t) + IIF(EMPTY(t), 'E', 'F') + ']'\n"
        "GO 2\nc = c + '[' + VARTYPE(t) + IIF(EMPTY(t), 'E', 'F') + ']'\n"
        "STRTOFILE(c, 'corrupt.txt')\nRETURN\n", message);
    expect(completed, "corrupt Julian day: the script should complete: " + message);
    const std::string output = read_file(dir / "corrupt.txt");
    // Neither is a valid DateTime: the runtime keeps its raw storage text (a Character value), as it does for any
    // unreadable DateTime, and the carried day never overflows.
    expect(output == "[CF][CF]", "corrupt Julian day: both values should stay unreadable text, got " + output);
    fs::remove_all(dir, ignored);
}

